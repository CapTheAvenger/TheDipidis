/* ── state ───────────────────────────────────────────────────── */
let currentLang = localStorage.getItem(I18N_STORAGE_KEY)
                  || I18N_DEFAULT_LANG;
if (!I18N_SUPPORTED.includes(currentLang)) currentLang = I18N_DEFAULT_LANG;

/* ── core API ────────────────────────────────────────────────── */

// Boot-time bootstrapping for lazy lang-packs is deferred to the bottom
// of this file (after _i18nLazyLoadLang is defined).

/**
 * Return the translated string for `key` in the current language.
 * Falls back to English, then returns the key itself if nothing found.
 */
function t(key) {
  const lang = translations[currentLang];
  if (lang && lang[key] !== undefined) return lang[key];
  const fallback = translations[I18N_DEFAULT_LANG];
  if (fallback && fallback[key] !== undefined) return fallback[key];
  return key;                     // last resort: show the key
}

/* ── lazy-loaded language packs ─────────────────────────────────
 *
 * Wave-1 L2.8: the `de` translation block (~100 KB) was split out into
 * js/i18n-de.js to keep the initial bundle small. That file registers
 * itself by calling window.__i18nRegisterLang('de', { ... }), which
 * installs the data into the local `translations` object and re-renders
 * the DOM if `de` is the current language.
 *
 * Until the lang-pack arrives, t() falls back to English
 * (I18N_DEFAULT_LANG), so the page never blocks waiting for translations.
 */
const _i18nPendingLoads = Object.create(null);

function _i18nLazyLoadLang(lang) {
  if (lang === I18N_DEFAULT_LANG) return Promise.resolve(); // always inline
  if (translations[lang]) return Promise.resolve();         // already loaded
  if (_i18nPendingLoads[lang]) return _i18nPendingLoads[lang];

  _i18nPendingLoads[lang] = new Promise((resolve, reject) => {
    const s = document.createElement('script');
    const v = (typeof window !== 'undefined' && /** @type {any} */ (window).APP_VERSION) || '';
    s.src = 'js/i18n-' + lang + '.js' + (v ? '?v=' + v : '');
    s.async = false;
    s.onload = () => resolve();
    s.onerror = () => {
      delete _i18nPendingLoads[lang];
      reject(new Error('i18n: failed to load lang pack ' + lang));
    };
    document.head.appendChild(s);
  });
  return _i18nPendingLoads[lang];
}

/** Lang-pack files call this to register their dictionary. */
/** @type {any} */ (window).__i18nRegisterLang = function (lang, data) {
  translations[lang] = data;
  if (lang === currentLang) {
    try { updateTranslationsInDOM(); } catch (_) { /* DOM not ready */ }
    document.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
  }
};

/**
 * Switch to `lang` (e.g. 'en' | 'de'), persist choice, update DOM.
 * For lazy lang-packs not yet loaded, kicks off the load and re-renders
 * once data arrives; in the meantime UI text falls back to English.
 * Dispatches a 'languageChanged' CustomEvent on document so other
 * modules (charts, dynamic tables) can re-render.
 */
function switchLanguage(lang) {
  if (!I18N_SUPPORTED.includes(lang)) return;
  currentLang = lang;
  localStorage.setItem(I18N_STORAGE_KEY, lang);
  document.documentElement.lang = lang;
  updateTranslationsInDOM();
  document.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
  // Trigger lazy load if needed; re-render happens automatically from
  // __i18nRegisterLang once data arrives.
  _i18nLazyLoadLang(lang).catch((err) => console.warn(err));
}

/**
 * Return the currently active language code ('en' | 'de').
 */
function getLang() {
  return currentLang;
}

/* ── DOM updater ─────────────────────────────────────────────── */

/**
 * Walk all elements with `data-i18n` and replace visible text.
 *
 * Supported attributes:
 *   data-i18n="key"              → sets innerHTML
 *   data-i18n-placeholder="key"  → sets placeholder
 *   data-i18n-title="key"        → sets title attribute
 *   data-i18n-aria="key"         → sets aria-label
 */
function updateTranslationsInDOM() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (!key) return;
    const translated = t(key);
    const childElements = Array.from(el.children);
    if (childElements.length > 0) {
      // If the element has a dedicated label child, update that instead
      const labelChild = el.querySelector('.menu-item-label');
      if (labelChild) {
        labelChild.textContent = translated;
        return;
      }
      // Preserve other child elements (e.g. info-icon spans) — only replace direct text
      const textNodes = Array.from(el.childNodes).filter(n => n.nodeType === Node.TEXT_NODE && n.textContent.trim());
      if (textNodes.length > 0) {
        textNodes[0].textContent = translated + ' ';
      }
      // If no text nodes exist, don't insert one (the element uses child elements for text)
    } else {
      el.innerHTML = translated;
    }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key && (el instanceof HTMLInputElement || el instanceof HTMLTextAreaElement)) {
      el.placeholder = t(key);
    }
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (key && el instanceof HTMLElement) el.title = t(key);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    const key = el.getAttribute('data-i18n-aria');
    if (key) el.setAttribute('aria-label', t(key));
  });

  // Update the language toggle button label (show active language)
  const toggle = document.getElementById('langToggleBtn');
  if (toggle) toggle.textContent = currentLang === 'de' ? 'DE' : 'EN';

  // Update CSS custom property for close-button tooltips
  document.documentElement.style.setProperty('--close-tooltip', `'${t('btn.close')}'`);
}

// Expose i18n functions globally
window.t = t;
window.switchLanguage = switchLanguage;
window.getLang = getLang;
window.updateTranslationsInDOM = updateTranslationsInDOM;

/* ── auto-init on load ───────────────────────────────────────── */
// Kick off lazy lang-pack load IMMEDIATELY if the user's saved language
// isn't English. We do this at module load (i.e. as soon as i18n.js
// finishes executing as part of the legacy bundle) rather than waiting
// for DOMContentLoaded — fetch can run concurrently with the rest of
// the bundle's parse so the lang pack lands sooner.
if (currentLang !== I18N_DEFAULT_LANG && !translations[currentLang]) {
  _i18nLazyLoadLang(currentLang).catch((err) => console.warn(err));
}

document.addEventListener('DOMContentLoaded', () => {
  document.documentElement.lang = currentLang;
  updateTranslationsInDOM();
});
