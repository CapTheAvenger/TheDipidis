def test_deep_link_urls_round_trip(bot_index):
    """Every deck name must survive URL-encoding and URL-decoding without
    drift. Apostrophes (N's Zoroark, Cynthia's Garchomp, etc.) and
    spaces are the usual hazards."""
    tab_for_source = {
        "current-meta": "current-analysis",
        "past-tef-por": "past-meta",
        "city-league":  "city-league-analysis",
    }
    issues = []
    for deck in bot_index["decks"].values():
        name = deck["name"]
        for src_key, src in deck.get("sources", {}).items():
            tab = tab_for_source.get(src_key)
            if not tab:
                continue
            qs = {"deck": name}
            if src_key == "past-tef-por" and src.get("format_key"):
                qs["format"] = src["format_key"]
            url = f"https://thedipidis.app/#{tab}?{urllib.parse.urlencode(qs)}"

            # Parse it back the way js/inline-init.js does
            frag = urllib.parse.urlparse(url).fragment
            if "?" not in frag:
                issues.append((name, src_key, "no query in fragment"))
                continue
            params = urllib.parse.parse_qs(frag.split("?", 1)[1])
            roundtripped = params.get("deck", [""])[0]
            if roundtripped != name:
                issues.append((name, src_key, f"roundtrip drift: {roundtripped!r}"))
    assert not issues, (
        "Deep-link URL encoding does not round-trip cleanly for some decks:\n  "
        + "\n  ".join(f"{n} / {s}: {why}" for n, s, why in issues[:10])
    )
