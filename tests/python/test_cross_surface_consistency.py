"""Cross-surface consistency between the bot deck index, the website's
matchup CSV, and the deck-name source the website dropdowns read.

The bot, the "Matchups vs Meta Call" panel, and the deck-select
dropdown on /current-analysis all build their UI from the same data
roots. Diffs between them are user-visible bugs (numbers that don't
match across two tabs, deep-links that land on a tab but don't
pre-select the deck, etc.). This suite pins:

  • Bot's current-meta matchup values agree with the raw Limitless
    online CSV — but tolerates the labs blend on pairs that have
    enough labs samples (MAJOR_MATCHUP_MIN_GAMES = 10).
  • Every bot deck name is present in the website source the
    dropdown reads — so each deep-link's ?deck=… actually pre-selects
    an option instead of leaving the field blank.
  • Deep-link URL encoding round-trips for every deck (apostrophes,
    spaces, the works).

Sources:
  • Bot deck index: data/bot-deck-index.json (generated by
    scripts/generate-bot-deck-index.py during the Pages deploy).
  • Website matchup source: data/limitless_online_decks_matchups.csv
    (read raw by js/app-current-meta-analysis.js:1804).
  • Website dropdown source: data/current_meta_card_data.csv
    archetype column (read by js/app-current-meta-analysis.js).
"""

