# Same threshold the generator uses to decide whether to blend labs in
# (scripts/generate-bot-deck-index.py:MAJOR_MATCHUP_MIN_GAMES = 10).
# Pairs above this can legitimately differ from the raw online value;
# pairs below it must match the online value exactly.
MAJOR_MATCHUP_MIN_GAMES = 10


def test_bot_matchups_match_website_panel_when_no_blend(bot_index, limitless_matchups):
    """For each (deck, opponent) the bot surfaces, when no labs blend
    was applied (= labs sample below threshold), the win-pct must
    match the raw Limitless CSV exactly. Blended pairs are skipped —
    they're allowed to differ by design.

    The CSV holds win-rates as percentages with 0.1pp precision, so we
    tolerate a tiny floating-point delta only.
    """
    diffs = []
    for deck in bot_index.get("decks", {}).values():
        src = deck.get("sources", {}).get("current-meta")
        if not src:
            continue
        name = deck["name"]
        for m in src.get("matchups", []):
            opp = m.get("opponent")
            bot_wr = float(m.get("win_pct", 0))
            online = limitless_matchups.get(name, {}).get(opp)
            if not online:
                continue  # bot has the pair, website doesn't — different concern
            web_wr = online["wr"]
            # If the pair could have been blended, skip the strict check
            web_games = online["games"]
            if bot_wr != round(web_wr, 1):
                # The drift can be due to labs blend (sample large enough)
                # or a real inconsistency. The bot's "games" field on a
                # blended pair is online + labs combined; on raw it equals
                # the online sample. Use that gap to spot the labs branch.
                if abs(m.get("games", 0) - web_games) > 0:
                    continue  # labs blended → legitimate diff
                diffs.append((name, opp, bot_wr, web_wr))
    assert not diffs, (
        "Bot shows different matchup numbers than the website panel for "
        "pairs that should be raw online (no labs blend):\n  "
        + "\n  ".join(f"{n} vs {o}: bot={b:.1f}% web={w:.1f}%" for n, o, b, w in diffs[:10])
    )


def test_bot_current_deck_names_exist_in_website_source(bot_index, website_current_archetypes):
    """Every name the bot embeds in a current-meta deep-link
    (#current-analysis?deck=…) must exist as an option in the
    /current-analysis dropdown — otherwise the user lands on the tab
    but the dropdown stays blank."""
    bot_names = {
        d["name"] for d in bot_index["decks"].values()
        if "current-meta" in d.get("sources", {})
    }
    missing = bot_names - website_current_archetypes
    assert not missing, (
        "Bot exposes current-meta decks that don't exist in the website's "
        "deck-select source (current_meta_card_data.csv archetype column). "
        "Deep-links to these decks will land on the tab but won't pre-select:\n  "
        + "\n  ".join(sorted(missing)[:10])
    )


def test_bot_past_deck_names_exist_in_website_source(bot_index, website_past_archetypes):
    """Same as above for past-meta deep-links (#past-meta?deck=…&format=TEF-POR)."""
